"""Catalog every skill and rule across the jeby repos; install the promoted ones globally.

Usage (from anywhere):
  python standards/scripts/sync_skills.py            # rebuild standards/skills/CATALOG.md + catalog.json
  python standards/scripts/sync_skills.py --install  # also copy promoted skills into ~/.claude/skills/
  python standards/scripts/sync_skills.py --check    # exit 1 if the catalog is stale (for hooks and CI)

A skill is any SKILL.md under .agents/skills/<name>/ or .claude/skills/<name>/ in a repo. Rules are
.claude/rules/*.md. AGENTS.md and CLAUDE.md are listed as a repo's operating files. .venv, node_modules,
site-packages and .git are skipped. Descriptions come from YAML frontmatter when present.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

SKIP = {".venv", "node_modules", "site-packages", ".git", ".tmp.drivedownload", ".tmp.driveupload",
        "dist", "build", ".desk", "__pycache__"}


def frontmatter_description(path: Path) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    if m:
        d = re.search(r"^description:\s*(.+)$", m.group(1), re.M)
        if d:
            return d.group(1).strip().strip('"').strip("'")
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and not line.startswith("---"):
            return line[:160]
    return ""


def walk(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP]
        yield Path(dirpath), filenames


def rel(p: Path, root: Path) -> str:
    return str(p.relative_to(root)).replace("\\", "/")


def scan(root: Path) -> dict:
    skills, rules, operating = [], [], []
    for d, files in walk(root):
        parts = d.relative_to(root).parts
        repo = parts[0] if parts else "."
        if "SKILL.md" in files and len(parts) >= 3 and parts[-3] in (".agents", ".claude") and parts[-2] == "skills":
            p = d / "SKILL.md"
            skills.append({"name": parts[-1], "repo": repo, "path": rel(p, root),
                           "description": frontmatter_description(p),
                           "sha256": hashlib.sha256(p.read_bytes()).hexdigest()[:12]})
        if len(parts) >= 2 and parts[-2] == ".claude" and parts[-1] == "rules":
            for f in files:
                if f.endswith(".md"):
                    p = d / f
                    rules.append({"name": f, "repo": repo, "path": rel(p, root),
                                  "description": frontmatter_description(p)})
        for f in files:
            if f in ("AGENTS.md", "CLAUDE.md") and len(parts) <= 2:
                operating.append({"name": f, "repo": repo, "path": rel(d / f, root)})
    for lst in (skills, rules, operating):
        lst.sort(key=lambda s: (s["repo"], s["name"]))
    return {"skills": skills, "rules": rules, "operating": operating}


def render(cat: dict) -> str:
    out = ["# Skills catalog (generated)", "",
           "Generated by `standards/scripts/sync_skills.py`. Do not edit by hand. Every skill, rule and operating file",
           "found across the repos under the umbrella. Promote a skill by adding its name to `promoted.txt` (a Desk ticket),",
           "then run `--install`.", "",
           f"Skills: {len(cat['skills'])} · Rules: {len(cat['rules'])} · Operating files: {len(cat['operating'])}", "",
           "## Skills", "", "| Skill | Repo | Description | Path |", "| --- | --- | --- | --- |"]
    for s in cat["skills"]:
        out.append(f"| `{s['name']}` | {s['repo']} | {s['description'].replace('|', '/')} | `{s['path']}` |")
    out += ["", "## Path-scoped rules", "", "| Rule | Repo | Description | Path |", "| --- | --- | --- | --- |"]
    for r in cat["rules"]:
        out.append(f"| `{r['name']}` | {r['repo']} | {r['description'].replace('|', '/')} | `{r['path']}` |")
    out += ["", "## Operating files", "", "| File | Repo | Path |", "| --- | --- | --- |"]
    for o in cat["operating"]:
        out.append(f"| `{o['name']}` | {o['repo']} | `{o['path']}` |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=None, help="umbrella root (default: the parent of standards/)")
    ap.add_argument("--install", action="store_true", help="copy promoted skills into ~/.claude/skills/")
    ap.add_argument("--check", action="store_true", help="exit 1 if CATALOG.md is stale")
    a = ap.parse_args()
    here = Path(__file__).resolve()
    root = Path(a.root).resolve() if a.root else here.parents[2]
    skills_dir = here.parents[1] / "skills"
    skills_dir.mkdir(parents=True, exist_ok=True)
    cat = scan(root)
    text = render(cat)
    md, js = skills_dir / "CATALOG.md", skills_dir / "catalog.json"
    if a.check:
        stale = (not md.exists()) or md.read_text(encoding="utf-8") != text
        print("catalog stale" if stale else "catalog current")
        return 1 if stale else 0
    md.write_text(text, encoding="utf-8", newline="\n")
    js.write_text(json.dumps(cat, indent=2), encoding="utf-8", newline="\n")
    print(f"wrote {md} ({len(cat['skills'])} skills, {len(cat['rules'])} rules, {len(cat['operating'])} operating files)")
    if a.install:
        promoted_file = skills_dir / "promoted.txt"
        promoted = [l.strip() for l in promoted_file.read_text(encoding="utf-8").splitlines()
                    if l.strip() and not l.startswith("#")] if promoted_file.exists() else []
        target = Path.home() / ".claude" / "skills"
        target.mkdir(parents=True, exist_ok=True)
        by_name = {s["name"]: s for s in cat["skills"]}
        for name in promoted:
            s = by_name.get(name)
            if not s:
                print(f"  promoted skill not found in any repo: {name}", file=sys.stderr)
                continue
            src = (root / s["path"]).parent
            dst = target / name
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
            print(f"  installed {name} <- {s['repo']}")
        if not promoted:
            print("  nothing promoted yet (standards/skills/promoted.txt is empty)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
